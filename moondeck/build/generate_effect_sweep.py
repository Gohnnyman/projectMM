#!/usr/bin/env python3
"""Generate the effect list the grid-size sweep test drives.

The sweep (`test/unit/light/unit_Effects_gridsweep.cpp`) must cover EVERY effect,
including ones that do not exist yet — a hand-written list would silently miss the next
effect someone adds, which is exactly the gap the sweep exists to close. The test binary
does not link `main.cpp` (where the factory registrations live), so it cannot ask the
factory either.

So the list is derived from the filesystem: every `src/light/effects/*Effect.h` becomes an
include + a registration line in a generated header the test includes. Add an effect file,
and the sweep covers it on the next build with no test edit.

Usage:
  uv run moondeck/build/generate_effect_sweep.py <output-header>
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
EFFECTS = ROOT / "src" / "light" / "effects"

# Headers that are not a concrete, default-constructible effect the sweep can instantiate.
#   EffectBase          the abstract base itself
#   MoonLiveEffect      runs a user-supplied script; with no script loaded it is a no-op,
#                       and its JIT path is covered by its own tests
_SKIP = {"EffectBase", "MoonLiveEffect"}


def effect_stems():
    """Every concrete effect header stem, sorted for a stable generated file."""
    return sorted(p.stem for p in EFFECTS.glob("*Effect.h") if p.stem not in _SKIP)


def render(stems):
    includes = "\n".join(f'#include "light/effects/{s}.h"' for s in stems)
    cases = "\n".join(
        f'    fn("{s}", [] {{ return static_cast<MoonModule*>(new {s}()); }});'
        for s in stems)
    return f"""// GENERATED by moondeck/build/generate_effect_sweep.py — do not edit.
//
// Every concrete effect header under src/light/effects/, as a name + constructor pair.
// Regenerated on every build, so an effect added to the tree is swept without touching
// the test.
//
// Deliberately NOT ModuleFactory registrations. The factory is a process-wide registry
// shared by every test in this binary, and `registerType` APPENDS unconditionally — the
// same name registered by several test files takes several slots (`Layer` and
// `RainbowEffect` are each registered many times over). Adding one entry per effect on
// top of that pushes `count_` (a uint8_t) toward its 255 ceiling, where `grow()` returns
// false and registration silently fails: the bool nobody checks. Constructing directly
// keeps the sweep independent of whatever else the binary has already registered, and of
// the order the tests happen to run in.
#pragma once

#include "core/MoonModule.h"
{includes}

namespace mm {{

// Call `fn(name, make)` once per effect. `make` returns a heap effect the caller owns.
template <typename F>
inline void forEachEffect(F fn) {{
{cases}
}}

}}  // namespace mm
"""


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)

    stems = effect_stems()
    if not stems:
        print(f"No effect headers found under {EFFECTS} — refusing to generate an empty "
              f"sweep (it would pass without testing anything).", file=sys.stderr)
        sys.exit(1)

    out = Path(sys.argv[1])
    out.parent.mkdir(parents=True, exist_ok=True)
    text = render(stems)
    # Only rewrite on change, so an unchanged effect set does not re-trigger the build.
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")
    print(f"Effect sweep list: {len(stems)} effects -> {out}")


if __name__ == "__main__":
    main()
